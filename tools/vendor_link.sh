#!/bin/sh
# Vendor Hearth's link layer into libs/ext/link (docs/SHARE.md).
#
#   sh tools/vendor_link.sh <hearth checkout>           copy the manifest files at Hearth's HEAD
#   sh tools/vendor_link.sh --check <hearth checkout>   diff the copy against the commit in LINK_SOURCE
#
# Hearth is the canonical home: the files listed in its tools/link-files.txt are
# copied from the committed tree (never the working copy), so what lands here
# is exactly a Hearth commit, named in libs/ext/link/LINK_SOURCE. A dirty
# Hearth tree is refused, so that commit is the whole truth. Fix bugs in Hearth
# and vendor again; never edit libs/ext/link/{core,net,proto} (--check fails).
#
# --check exits 0 on a faithful copy, 1 on drift, 77 when the checkout is not
# there (ctest reads that as a skip).
set -eu

dest=$(cd "$(dirname "$0")/.." && pwd)/libs/ext/link
mode=vendor
if [ "${1:-}" = "--check" ]; then
    mode=check
    shift
fi
[ $# -eq 1 ] || { echo "usage: $0 [--check] <hearth checkout>" >&2; exit 2; }
hearth=$1

if ! git -C "$hearth" rev-parse --git-dir >/dev/null 2>&1; then
    echo "$hearth is not a git checkout" >&2
    [ "$mode" = check ] && exit 77
    exit 2
fi

# libs/core/x -> core/x, proto/x -> proto/x: the include root is libs/ext/link.
vendored() { case $1 in libs/*) echo "${1#libs/}" ;; *) echo "$1" ;; esac; }
# Manifest on stdin, comments and blanks dropped.
manifest() { grep -v -e '^#' -e '^$'; }

if [ "$mode" = vendor ]; then
    if [ -n "$(git -C "$hearth" status --porcelain)" ]; then
        echo "refusing: $hearth has uncommitted changes" >&2
        exit 1
    fi
    sha=$(git -C "$hearth" rev-parse HEAD)
    files=$(git -C "$hearth" show "$sha:tools/link-files.txt" | manifest)
    rm -rf "$dest/core" "$dest/net" "$dest/proto"
    for f in $files; do
        mkdir -p "$dest/$(dirname "$(vendored "$f")")"
        git -C "$hearth" show "$sha:$f" >"$dest/$(vendored "$f")"
    done
    {
        echo "# Generated by tools/vendor_link.sh - do not edit. Fix in Hearth first, then vendor again."
        echo "commit: $sha"
        echo "date: $(git -C "$hearth" log -1 --format=%cI "$sha")"
        echo "manifest:"
        for f in $files; do echo "  $f"; done
    } >"$dest/LINK_SOURCE"
    echo "vendored hearth@$(echo "$sha" | cut -c1-7): $(echo "$files" | wc -l) files"
    exit 0
fi

sha=$(sed -n 's/^commit: //p' "$dest/LINK_SOURCE")
want=$(sed -n 's/^  //p' "$dest/LINK_SOURCE")
if ! git -C "$hearth" cat-file -e "$sha^{commit}" 2>/dev/null; then
    echo "$hearth has no commit $sha" >&2
    exit 1
fi
bad=0
# The manifest Hearth had at that commit must be the one recorded here.
[ "$(git -C "$hearth" show "$sha:tools/link-files.txt" | manifest)" = "$want" ] \
    || { echo "manifest at $sha differs from LINK_SOURCE" >&2; bad=1; }
for f in $want; do
    git -C "$hearth" show "$sha:$f" | cmp -s - "$dest/$(vendored "$f")" \
        || { echo "drift: $(vendored "$f")" >&2; bad=1; }
done
# A file nobody vendored is drift too.
extra=$( (cd "$dest" && find core net proto -type f 2>/dev/null) | sort)
expected=$(for f in $want; do vendored "$f"; done | sort)
[ "$extra" = "$expected" ] || { echo "file set differs from the manifest" >&2; bad=1; }
[ "$bad" -eq 0 ] && echo "libs/ext/link matches hearth@$(echo "$sha" | cut -c1-7)"
exit "$bad"
